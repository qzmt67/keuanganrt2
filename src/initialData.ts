export interface Resident {
  id: string;
  code: string;
  name: string;
  house: string;
  dawis: string;
  phone: string;
  rate: number;
  tunggakan: number;
  payments: { [key: string]: number };
}

export function parseResidents(): Resident[] {
  return RAW_RESIDENTS.map(([code, name, house, dawisNum, phone, rateK, tunggakanK, pays], idx) => {
    const payMap: { [key: string]: number } = {};
    MONTHS.forEach((m, mIdx) => {
      payMap[m] = (pays[mIdx] || 0) * 1000;
    });
    return {
      id: `w-${idx + 1}`,
      code,
      name,
      house,
      dawis: dawisNum > 0 ? `Dawis ${dawisNum}` : '-',
      phone,
      rate: rateK * 1000,
      tunggakan: tunggakanK * 1000,
      payments: payMap
    };
  });
}